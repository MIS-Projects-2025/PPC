    public function run(): void
    {
        $names = collect(preg_split('/\R/', $this->partnames()))
            ->map(fn($n) => trim($n))
            ->filter()
            ->unique()   // the pasted list contains a few duplicates
            ->values();

        $now = now();

        $names->chunk(200)->each(function ($chunk) use ($now) {
            DB::table('bosch_parts')->upsert(
                $chunk->map(fn($n) => [
                    'partname'   => $n,
                    'is_bosch'   => true,
                    'created_at' => $now,
                    'updated_at' => $now,
                ])->all(),
                ['partname'],               // unique key
                ['is_bosch', 'updated_at'], // columns to update on conflict
            );
        });

        Cache::forget('bosch-partnames:v1');
    }

